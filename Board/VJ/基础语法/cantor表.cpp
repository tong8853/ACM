void solve(){
    int n;
    cin >> n;
    int k = int(sqrt(n * 2 - 1.75) + 0.5);
    n -= (k - 1) * k / 2;
    if(k & 1) cout << k - n + 1 << '/' << n;
    else cout << n << '/' << k - n + 1;
}

int main(){
    ios::sync_with_stdio(0);
    cin.tie(0);
    int T = 1;
    //cin >> T;
    while(T--) solve();
    return 0;
}